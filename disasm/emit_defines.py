"""Write tailgunner_defines.asm: memory map, I/O, sound bits and RAM words.

Every identifier tailgunner_program_rom.asm uses is defined here. RAM usage
counts come from the traces (build/analysis.json): how many instructions
read and wrote each word, directly or through the I register.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import romset, names, hwinfo

DEFINES = os.path.join(HERE, "tailgunner_defines.asm")


def alias(name, value, comment, width=4):
    s = ".alias %-18s $%0*X" % (name, width, value)
    return (s.ljust(34) + " ;" + comment) if comment else s


def section(title):
    return ["", ";" + "-" * 34 + "[ %s ]" % title + "-" * 34]


def main():
    an = json.load(open(os.path.join(romset.BUILD, "analysis.json")))
    refs = json.load(open(os.path.join(romset.BUILD, "program_refs.json")))
    rr = {int(k): v for k, v in an["ram_r"].items()}
    rw = {int(k): v for k, v in an["ram_w"].items()}
    out = [
        ";Tailgunner (Cinematronics, 1979) - memory map, I/O and RAM words for",
        ";tailgunner_program_rom.asm.",
        ";The CCPU has separate program and data spaces: 8K of program ROM, fetched as",
        ";bytes, and 256 words of 12-bit data RAM, addressed as 16 pages of 16 words",
        ";(the P register picks the page, the opcode the word). I/O is not memory",
        ";mapped: INP reads one bit, OUT writes one bit, JMI tests the joystick.",
        ";Hardware notes are from the AAE Cinematronics driver (after MAME's cinemat.cpp).",
        ";RAM names are this disassembly's; unnamed words are RAM_xx. [rN wM] counts the",
        ";instructions that read / wrote the word in the traces (instructions, not",
        ";accesses; the power-on RAM clear at L000B is one of the writers of every word).",
        ";Generated by disasm/emit_defines.py.",
    ]
    out += section("Memory map")
    out += [
        alias("Bank0Rom", 0x0000, "Through $0FFF. tgunner.t70 (even bytes) + tgunner.p70 (odd bytes)."),
        alias("Bank1Rom", 0x1000, "Through $1FFF. tgunner.t71 (even bytes) + tgunner.p71 (odd bytes)."),
        alias("DataRam", 0x00, "Through $FF: 256 words x 12 bits, page = P register, word = opcode low nibble.", 2),
    ]
    out += section("Inputs (INP n with the A accumulator, active low)")
    for n, (nm, desc) in sorted(hwinfo.INPUTS.items()):
        out.append(alias(nm, n, desc, 1))
    out += section("Switches (INP n with the B accumulator)")
    for n, (nm, desc) in sorted(hwinfo.SWITCHES.items()):
        out.append(alias(nm, n, desc, 1))
    out += section("Outputs (OUT n writes the inverse of A bit 0)")
    for n, (nm, desc) in sorted(hwinfo.OUTPUTS.items()):
        out.append(alias(nm, n, desc, 1))
    out += [";JMI and JMIB jump when the stick axis that OUT_MUX selects is past the X register;",
            ";the game finds the stick position by successive tests."]
    out += section("Sound board register (written one bit at a time through OUT 0-4; 0 = on)")
    for n, desc in sorted(hwinfo.SOUND_BITS.items()):
        out.append(alias("SND_" + desc.upper(), n, "sound register bit %d: %s" % (n, desc), 1))
    out += section("Data RAM")
    used = set(rr) | set(rw) | set(names.RAM)
    for r in refs["ram"]:
        if r.startswith("RAM_"):
            used.add(int(r[4:], 16))
    for r in sorted(used):
        nm = names.RAM[r][0] if r in names.RAM else "RAM_%02X" % r
        desc = names.RAM[r][1] if r in names.RAM else ""
        for s in getattr(names, "RAM_BLOCKS", {}).get(r, []):
            out.append(";" + s)
        use = "r%d w%d" % (len(rr.get(r, [])), len(rw.get(r, [])))
        users = refs.get("ram_users", {}).get("%d" % r)
        if users:
            use += "; in " + ", ".join(users[:5]) + (" ..." if len(users) > 5 else "")
        out.append(alias(nm, r, (desc + "  " if desc else "") + "[" + use + "]", 2))
    # every name the listing can use, defined even when the traces never touched it
    missing = [r for r in refs["ram"] if r.startswith("RAM_") and int(r[4:], 16) not in used]
    assert not missing, missing
    with open(DEFINES, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s: %d RAM words (%d named)" % (DEFINES, len(used), len([r for r in used if r in names.RAM])))


if __name__ == "__main__":
    main()
